import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const root = 'public/resources/poster-design';
const output = 'public/images/poster-previews';
fs.mkdirSync(output, { recursive: true });
const previews = {};
let originalBytes = 0, previewBytes = 0;
for (const project of fs.readdirSync(root)) {
  const dir = path.join(root, project);
  if (!fs.statSync(dir).isDirectory()) continue;
  for (const file of fs.readdirSync(dir)) {
    if (!/\.(jpg|jpeg|png|webp)$/i.test(file)) continue;
    const source = path.join(dir, file);
    const meta = await sharp(source).metadata();
    const variants = [];
    originalBytes += fs.statSync(source).size;
    for (const width of [480, 960]) {
      const name = `${project}-${path.parse(file).name}-${width}.webp`;
      const dest = path.join(output, name);
      const result = await sharp(source).resize({ width, withoutEnlargement: true }).webp({ quality: 83 }).toFile(dest);
      variants.push({ path: `images/poster-previews/${name}`, width: result.width });
      previewBytes += result.size;
    }
    previews[`resources/poster-design/${project}/${file}`] = { width: meta.width, height: meta.height, variants };
  }
}
fs.writeFileSync('src/data/poster-previews.generated.ts', '// Generated by scripts/generate-poster-previews.mjs.\nexport const POSTER_PREVIEWS: Record<string, { width: number; height: number; variants: { path: string; width: number }[] }> = ' + JSON.stringify(previews, null, 2) + ';\n');
console.log(JSON.stringify({ posters: Object.keys(previews).length, originalBytes, previewBytes }));
